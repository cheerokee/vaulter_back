import {
  ConflictError,
  DomainValidationError,
} from '../../shared/domain/errors.js';
import { validate, version } from 'uuid';
import {
  cloudManifestObjectId,
  hubManifestObjectId,
} from '../../shared/domain/space-manifest-ids.js';
import { MAX_CONFIRM_BATCH_BYTES, MAX_OBJECT_BYTES } from './backup-limits.js';

/** What the rules need of the (locked) space. */
export type WritableSpace = {
  keyRotationRequired: boolean;
  currentKeyVersion: number;
  storageQuotaBytes: number;
};

export const BackupRules = {
  /**
   * New content only with the CURRENT key and no pending rotation (spec §4.2): content encrypted with a version that
   * someone who left knows is refused. 409 `space-key-rotation-required` / `space-key-version-stale`.
   */
  assertWritable(space: WritableSpace, keyVersion: number): void {
    if (space.keyRotationRequired) {
      throw new ConflictError(
        'space-key-rotation-required',
        'The space key must be rotated before new content is accepted.',
      );
    }
    if (keyVersion !== space.currentKeyVersion) {
      throw new ConflictError(
        'space-key-version-stale',
        'The content must be encrypted with the current key version of the space.',
        { currentKeyVersion: space.currentKeyVersion },
      );
    }
  },

  /** 422 `object-too-large` above 5 GiB (the hub splits bigger files). */
  assertObjectSize(objectId: string, sizeBytes: number): void {
    if (sizeBytes > MAX_OBJECT_BYTES) {
      throw new DomainValidationError(
        'object-too-large',
        `An object can have at most ${MAX_OBJECT_BYTES} bytes.`,
        { objectId, maxBytes: MAX_OBJECT_BYTES },
      );
    }
  },

  /** `usedBytes` (committed + trash + live reservations) + `extraBytes` must fit the space size. */
  assertFits(
    space: WritableSpace,
    usedBytes: number,
    extraBytes: number,
  ): void {
    const missingBytes = usedBytes + extraBytes - space.storageQuotaBytes;
    if (missingBytes > 0) {
      throw new DomainValidationError(
        'space-storage-full',
        'The space does not have room for these objects.',
        { missingBytes },
      );
    }
  },

  /** 422 `confirm-batch-too-large` when one confirmation would copy more than 5 GiB (declared sizes). */
  assertConfirmBatchSize(requestedBytes: number): void {
    if (requestedBytes > MAX_CONFIRM_BATCH_BYTES) {
      throw new DomainValidationError(
        'confirm-batch-too-large',
        `One confirmation can copy at most ${MAX_CONFIRM_BATCH_BYTES} bytes; confirm in smaller batches.`,
        { maxBytes: MAX_CONFIRM_BATCH_BYTES, requestedBytes },
      );
    }
  },

  /**
   * Object ids a Hub or a person may write (docs/hubs/space-manifest.md): a UUID v7 generated by the Hub/app, or the
   * fixed id of the space's Hub manifest (UUID v5). The cloud manifest's id is written only by the server: 422
   * `object-id-reserved` (upload and delete); any other id: 422 `object-id-invalid`. A malformed space id is left to the
   * access check (404).
   */
  assertObjectIdWritable(spaceId: string, objectId: string): void {
    if (!validate(spaceId)) return;
    if (objectId === cloudManifestObjectId(spaceId)) {
      throw new DomainValidationError(
        'object-id-reserved',
        'This object id is reserved for the server.',
        { objectId },
      );
    }
    if (validate(objectId) && version(objectId) === 7) return;
    if (objectId === hubManifestObjectId(spaceId)) return;
    throw new DomainValidationError(
      'object-id-invalid',
      "An object id must be a UUID v7 or the space's manifest id.",
      { objectId },
    );
  },

  /**
   * The server's own writes (`ServerBackupWriter`: active cloud documents and the cloud manifest): a UUID v7 or the
   * cloud manifest's id of this space (never the Hub's manifest: the Hub owns it).
   */
  assertObjectIdServerWritable(spaceId: string, objectId: string): void {
    if (validate(objectId) && version(objectId) === 7) return;
    if (validate(spaceId) && objectId === cloudManifestObjectId(spaceId)) {
      return;
    }
    throw new DomainValidationError(
      'object-id-invalid',
      'The server writes UUID v7 objects or the cloud manifest only.',
      { objectId },
    );
  },

  /** Deleting: only the cloud manifest is refused (422 `object-id-reserved`). */
  assertObjectIdDeletable(spaceId: string, objectId: string): void {
    if (validate(spaceId) && objectId === cloudManifestObjectId(spaceId)) {
      throw new DomainValidationError(
        'object-id-reserved',
        'This object id is reserved for the server.',
        { objectId },
      );
    }
  },

  /** One item per object in a request. */
  assertDistinctObjects(objectIds: readonly string[]): void {
    if (new Set(objectIds).size !== objectIds.length) {
      throw new DomainValidationError(
        'duplicate-object',
        'An object can appear only once per request.',
      );
    }
  },
};
