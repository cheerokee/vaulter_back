import { ConflictError } from '../../shared/domain/errors.js';

export type BackupObjectProps = {
  id: string;
  organizationId: string;
  spaceId: string;
  /** The last committed version (kept after a delete: it is what the trash shows). */
  currentVersionId: string | null;
  deletedAt: Date | null;
};

/** 409: the object's live version is not the one the write says it replaces (or the id is another space's). */
export function objectVersionConflict(
  objectId: string,
  currentVersionId: string | null,
): ConflictError {
  return new ConflictError(
    'object-version-conflict',
    'The object changed since the version being replaced.',
    { objectId, currentVersionId },
  );
}

/**
 * An object of a space's backup: the `objectId` is generated by the hub and stable (a new upload of the same file is a
 * new version of the same object). The index never holds a name, type or path: only ids, sizes and hashes.
 * Optimistic concurrency between hubs (spec §4.2): every write says which version it replaces (`null` for a new or
 * deleted object); anything else is 409 `object-version-conflict`.
 */
export class BackupObject {
  private constructor(private props: BackupObjectProps) {}

  static restore(props: BackupObjectProps): BackupObject {
    return new BackupObject({ ...props });
  }

  /** The object as the writers see it: the committed version, or null when it never had one or was deleted. */
  get liveVersionId(): string | null {
    return this.props.deletedAt ? null : this.props.currentVersionId;
  }

  assertReplaces(replacesVersionId: string | null): void {
    if (replacesVersionId !== this.liveVersionId) {
      throw objectVersionConflict(this.props.id, this.liveVersionId);
    }
  }

  /** The new version becomes current (a deleted object comes back); returns the version it supersedes, if any. */
  commit(versionId: string): { supersededVersionId: string | null } {
    const supersededVersionId = this.liveVersionId;
    this.props = {
      ...this.props,
      currentVersionId: versionId,
      deletedAt: null,
    };
    return { supersededVersionId };
  }

  /**
   * Tombstone (the last version goes to the trash). Deleting again with the same `replacesVersionId` is a no-op
   * (`unchanged`: the hub retried); anything else that does not match is a conflict.
   */
  delete(
    replacesVersionId: string,
    now: Date,
  ):
    | { outcome: 'deleted'; supersededVersionId: string }
    | { outcome: 'unchanged' } {
    if (
      this.props.deletedAt &&
      replacesVersionId === this.props.currentVersionId
    ) {
      return { outcome: 'unchanged' };
    }
    const live = this.liveVersionId;
    if (live === null || replacesVersionId !== live) {
      throw objectVersionConflict(this.props.id, live);
    }
    this.props = { ...this.props, deletedAt: now };
    return { outcome: 'deleted', supersededVersionId: live };
  }

  get id(): string {
    return this.props.id;
  }
  get organizationId(): string {
    return this.props.organizationId;
  }
  get spaceId(): string {
    return this.props.spaceId;
  }
  get currentVersionId(): string | null {
    return this.props.currentVersionId;
  }
  get deletedAt(): Date | null {
    return this.props.deletedAt;
  }
}
