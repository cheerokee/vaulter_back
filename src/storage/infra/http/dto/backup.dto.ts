import { Type } from 'class-transformer';
import {
  ArrayMaxSize,
  ArrayMinSize,
  ArrayUnique,
  IsArray,
  IsIn,
  IsInt,
  IsISO8601,
  IsOptional,
  IsString,
  IsUUID,
  Matches,
  Max,
  MaxLength,
  Min,
  ValidateIf,
  ValidateNested,
} from 'class-validator';
import {
  MAX_BATCH_ITEMS,
  MAX_LIST_LIMIT,
} from '../../../domain/backup-limits.js';

const SHA256_HEX = /^[0-9a-f]{64}$/;
const BASE64URL = /^[A-Za-z0-9_-]+$/;
const INT32_MAX = 2_147_483_647;

/** One object to upload: ids, key version, size and sha256 of the ENCRYPTED blob (never a name). */
export class UploadIntentItemDto {
  /**
   * Stable id generated by the hub (UUID v7), or the space's Hub manifest id (UUID v5, docs/hubs/space-manifest.md);
   * any other UUID v5: 422 `object-id-invalid`; the cloud manifest id: 422 `object-id-reserved`.
   */
  @IsUUID(['5', '7'])
  objectId!: string;

  /** Must be the current key version of the space (else 409 space-key-version-stale). */
  @IsInt()
  @Min(1)
  @Max(INT32_MAX)
  keyVersion!: number;

  /** Exact size of the encrypted blob; above 5 GiB is 422 object-too-large (the hub splits bigger files). */
  @IsInt()
  @Min(1)
  @Max(Number.MAX_SAFE_INTEGER)
  sizeBytes!: number;

  /** Lowercase hex sha256 of the encrypted blob. */
  @IsString()
  @Matches(SHA256_HEX)
  sha256!: string;

  /** The version this upload replaces; `null` (explicit) for a new or deleted object. */
  @ValidateIf((_o, value) => value !== null)
  @IsUUID()
  replacesVersionId!: string | null;
}

export class UploadIntentDto {
  @IsArray()
  @ArrayMinSize(1)
  @ArrayMaxSize(MAX_BATCH_ITEMS)
  @ValidateNested({ each: true })
  @Type(() => UploadIntentItemDto)
  items!: UploadIntentItemDto[];
}

export class ConfirmUploadsDto {
  @IsArray()
  @ArrayMinSize(1)
  @ArrayMaxSize(MAX_BATCH_ITEMS)
  @ArrayUnique()
  @IsUUID('all', { each: true })
  uploadIds!: string[];
}

export class DeleteObjectItemDto {
  @IsUUID()
  objectId!: string;

  /** The live version being deleted (else 409 object-version-conflict). */
  @IsUUID()
  replacesVersionId!: string;
}

export class DeleteObjectsDto {
  @IsArray()
  @ArrayMinSize(1)
  @ArrayMaxSize(MAX_BATCH_ITEMS)
  @ValidateNested({ each: true })
  @Type(() => DeleteObjectItemDto)
  items!: DeleteObjectItemDto[];
}

export const OBJECT_LISTINGS = ['current', 'trash', 'versions'] as const;

/** `GET .../objects`: cursor by id; `since` (ISO 8601) only with current/trash; `objectId` only with versions. */
export class ListObjectsQueryDto {
  @IsOptional()
  @IsIn(OBJECT_LISTINGS)
  include: (typeof OBJECT_LISTINGS)[number] = 'current';

  /** Objects whose index row changed at or after this instant (use the `asOf` of a previous listing, minus a margin). */
  @IsOptional()
  @IsISO8601({ strict: true, strictSeparator: true })
  since?: string;

  /** The object whose stored versions to list (`include=versions`). */
  @IsOptional()
  @IsUUID()
  objectId?: string;

  @IsOptional()
  @IsString()
  @MaxLength(200)
  cursor?: string;

  @IsOptional()
  @Type(() => Number)
  @IsInt()
  @Min(1)
  @Max(MAX_LIST_LIMIT)
  limit: number = 100;
}

/** Empty the trash of the space (Gestor): the reauthentication proof of the current password. */
export class EmptyTrashDto {
  @IsString()
  @Matches(BASE64URL)
  @MaxLength(256)
  currentAuthProof!: string;
}
